"""
MCP Server (path B): expose this project's RAG + simple tools over MCP.

Run standalone (for Claude Desktop / Cursor / other MCP hosts):
    python -m backend.mcp_rag_server

Or via stdio from an MCP client (default when no args).
"""

from __future__ import annotations

import sys
from pathlib import Path

# ensure project root on path when run as script
ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mcp.server.fastmcp import FastMCP

from backend.rag import format_context, search_documents, collection_stats
from backend import reports as R

mcp = FastMCP(
    "rag-agent-tools",
    instructions="RAG search and report tools from the RAG Agent chatbot project",
)


@mcp.tool()
def search_knowledge_base(query: str) -> str:
    """Semantic search over the uploaded knowledge base (Chroma / RAG)."""
    hits = search_documents((query or "").strip())
    if not hits:
        return "No matching documents. Knowledge base may be empty — run ingest first."
    return format_context(hits)


@mcp.tool()
def knowledge_base_stats() -> str:
    """Return how many chunks are in the vector database."""
    s = collection_stats()
    return f"chunks={s.get('count', 0)}"


@mcp.tool()
def list_generated_reports() -> str:
    """List report files generated by the agent (outputs/)."""
    return R.list_output_files()


@mcp.tool()
def create_text_report(title: str, content: str) -> str:
    """Create a Word (.docx) report from title + content. Returns download path info."""
    info = R.create_docx_report(title or "Report", content or "")
    if info.get("error"):
        return str(info["error"])
    return f"Created {info['filename']} url={info['url']}"


def main():
    # stdio transport — standard for local MCP hosts
    mcp.run(transport="stdio")


if __name__ == "__main__":
    main()
